import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const source = join(root, "content", "cms", "site_copy");
const settingsSource = join(root, "content", "cms", "settings");
const copy = {};
const careers = {};
const ui = {};
const locales = new Set(["en", "it", "fr", "es", "de"]);

if (existsSync(source)) {
  for (const file of readdirSync(source).filter((name) => name.endsWith(".json"))) {
    try {
      const parsed = JSON.parse(readFileSync(join(source, file), "utf8"));
      const data = parsed.data && typeof parsed.data === "object" ? parsed.data : parsed;
      const slug = String(parsed.slug || file.replace(/\.json$/, ""));
      if (locales.has(slug)) copy[slug] = data;
      else if (slug.startsWith("careers-")) careers[slug.slice("careers-".length)] = data;
      else if (slug.startsWith("ui-")) ui[slug.slice("ui-".length)] = data;
    } catch (error) {
      console.warn(`cms-copy: invalid ${file}`, error);
    }
  }
}

// Le impostazioni del sito finiscono in un modulo generato, non lette a runtime:
// `lib/site.ts` e' importato da componenti client (footer, contatti, sezioni),
// e se trascinasse `node:fs` il bundle browser non si puo' piu' costruire.
// Generare qui tiene la separazione: il pannello scrive il JSON, il prebuild lo
// congela in TypeScript, e il client vede un oggetto.
let settings = {};
const settingsFile = join(settingsSource, "site.json");
if (existsSync(settingsFile)) {
  try {
    const parsed = JSON.parse(readFileSync(settingsFile, "utf8"));
    settings = parsed.data && typeof parsed.data === "object" ? parsed.data : parsed;
    delete settings.slug;
  } catch (error) {
    console.warn("cms-settings: invalid site.json", error);
  }
}

// L'indice delle pagine pubblicate dal pannello, per lo stesso motivo: il footer
// e' un client component e deve poterle elencare senza leggere il filesystem.
// Passarlo dal layout funzionava, ma iniettava l'elenco nell'HTML di ogni pagina
// e il peso della home superava il tetto di `verify.js`: qui resta un modulo.
const pages = [];
const pagesSource = join(root, "content", "cms", "page");
if (existsSync(pagesSource)) {
  for (const file of readdirSync(pagesSource).filter((name) => name.endsWith(".json"))) {
    try {
      const parsed = JSON.parse(readFileSync(join(pagesSource, file), "utf8"));
      if (typeof parsed.slug !== "string" || !Array.isArray(parsed.content)) continue;
      pages.push({
        slug: parsed.slug,
        title: String(parsed.title || parsed.slug),
        locales: Array.isArray(parsed.locales) ? parsed.locales.filter((entry) => typeof entry === "string") : ["en"],
        noindex: parsed.noindex === true,
      });
    } catch (error) {
      console.warn(`cms-pages: invalid ${file}`, error);
    }
  }
}

const output = `// Generated by scripts/gen-cms-copy.mjs. Do not edit by hand.\nexport const cmsCopyOverrides: Record<string, Record<string, unknown>> = ${JSON.stringify(copy, null, 2)};\nexport const cmsCareersUiOverrides: Record<string, Record<string, unknown>> = ${JSON.stringify(careers, null, 2)};\nexport const cmsUiOverrides: Record<string, Record<string, unknown>> = ${JSON.stringify(ui, null, 2)};\nexport const cmsSiteSettings: Record<string, unknown> = ${JSON.stringify(settings, null, 2)};\nexport const cmsPageIndex: Array<{ slug: string; title: string; locales: string[]; noindex: boolean }> = ${JSON.stringify(pages, null, 2)};\n`;
const destination = join(root, "lib", "generated", "cms-copy.ts");
mkdirSync(join(root, "lib", "generated"), { recursive: true });
const previous = existsSync(destination) ? readFileSync(destination, "utf8") : "";
if (previous !== output) writeFileSync(destination, output);
console.log(`cms-copy: ${Object.keys(copy).length + Object.keys(careers).length + Object.keys(ui).length} override file(s), ${pages.length} page(s), settings ${Object.keys(settings).length ? "on" : "default"}`);
